(() => {
  const PAGE_W = 612;
  const PAGE_H = 792;
  const palette = {
    slate: "#6D8196", charcoal: "#4A4A4A", green: "#879987",
    ivory: "#F3F5F7", gray: "#CBCBCB", ink: "#29313A", muted: "#707984",
    line: "#E1E6EB", white: "#FFFFFF"
  };
  const rgb = hex => {
    const v = hex.replace("#", "");
    return [0, 2, 4].map(i => parseInt(v.slice(i, i + 2), 16) / 255);
  };
  const colorOp = (hex, stroke = false) => `${rgb(hex).map(v => v.toFixed(3)).join(" ")} ${stroke ? "RG" : "rg"}`;
  const ascii = value => String(value).normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[^\x20-\x7e]/g, "-");
  const pdfText = value => ascii(value).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  const money = value => "$" + Number(value || 0).toLocaleString("en-US", { maximumFractionDigits: 0 });

  function makeReport(data) {
    let ops = [];
    const rect = (x, top, w, h, fill) => {
      ops.push(colorOp(fill), `${x} ${PAGE_H - top - h} ${w} ${h} re f`);
    };
    const line = (x1, top1, x2, top2, stroke = palette.line, width = 1) => {
      ops.push(colorOp(stroke, true), `${width} w`, `${x1} ${PAGE_H - top1} m ${x2} ${PAGE_H - top2} l S`);
    };
    const text = (x, top, value, size = 10, fill = palette.ink, bold = false) => {
      ops.push(colorOp(fill), `BT /${bold ? "F2" : "F1"} ${size} Tf ${x} ${PAGE_H - top} Td (${pdfText(value)}) Tj ET`);
    };
    rect(0, 0, PAGE_W, 105, palette.charcoal);
    text(42, 43, "Budget report", 23, palette.white, true);
    text(42, 68, data.period || "Budget summary", 11, "#E7EBEF");

    const cards = [
      ["Income", data.income], ["Expenses", data.total], [data.left >= 0 ? "Left over" : "Over budget", Math.abs(data.left)]
    ];
    const cardW = 166;
    cards.forEach(([label, value], i) => {
      const x = 42 + i * 176;
      rect(x, 123, cardW, 62, palette.ivory);
      text(x + 13, 146, label, 9, palette.muted);
      text(x + 13, 171, money(value), 17, i === 2 && data.left < 0 ? "#985F55" : palette.ink, true);
    });

    text(42, 222, "Income allocation", 13, palette.ink, true);
    text(42, 239, "How this period's income is assigned", 9, palette.muted);
    const allocation = [
      ["Needs", data.needs, palette.slate], ["Wants", data.wants, palette.charcoal],
      ["Savings", data.saved_category, palette.green], ["Unspent", Math.max(data.left, 0), palette.gray]
    ];
    const allocationTotal = Math.max(Number(data.income), Number(data.total), 1);
    let x = 42;
    const barW = 528;
    allocation.forEach(([, amount, fill]) => {
      const w = barW * Math.max(0, Number(amount)) / allocationTotal;
      if (w > 0) rect(x, 252, w, 13, fill);
      x += w;
    });
    allocation.forEach(([label, amount, fill], i) => {
      const lx = 42 + (i % 2) * 270;
      const ly = 287 + Math.floor(i / 2) * 20;
      rect(lx, ly - 8, 8, 8, fill);
      text(lx + 14, ly, `${label}  ${money(amount)}`, 9, palette.ink);
    });

    const guidelines = data.guidelines || { Needs: 50, Wants: 30, Saved: 20 };
    text(42, 340, `${data.guideline_name || "50/30/20"} guideline`, 13, palette.ink, true);
    text(42, 357, "Solid bar: your budget     Marker: guideline", 9, palette.muted);
    const ruleRows = [
      ["Needs", data.needs, guidelines.Needs, palette.slate], ["Wants", data.wants, guidelines.Wants, palette.charcoal],
      ["Saved", data.saved, guidelines.Saved, palette.green]
    ];
    ruleRows.forEach(([label, amount, target, fill], i) => {
      const top = 383 + i * 34;
      const pct = Number(amount) / Math.max(Number(data.income), 1) * 100;
      text(42, top + 9, label, 9, palette.ink, true);
      text(94, top + 9, `${Math.round(pct)}% / ${target}%`, 8, palette.muted);
      rect(180, top, 340, 8, "#EEF0F2");
      rect(180, top, 340 * Math.min(pct, 100) / 100, 8, fill);
      line(180 + 340 * target / 100, top - 3, 180 + 340 * target / 100, top + 11, palette.charcoal, 1.5);
    });

    text(42, 505, "Largest categories", 13, palette.ink, true);
    text(42, 522, "Share of income", 9, palette.muted);
    const categories = [...(data.categories || [])].sort((a, b) => b.amount - a.amount).slice(0, 8);
    const maxPct = Math.max(10, ...categories.map(c => Number(c.amount) / Math.max(Number(data.income), 1) * 100));
    categories.forEach((item, i) => {
      const top = 545 + i * 25;
      const pct = Number(item.amount) / Math.max(Number(data.income), 1) * 100;
      const fill = item.group === "Needs" ? palette.slate : item.group === "Savings" ? palette.green : palette.charcoal;
      text(42, top + 8, ascii(item.name).slice(0, 25), 8.5, palette.ink);
      rect(190, top, 290, 8, "#EEF0F2");
      rect(190, top, 290 * pct / maxPct, 8, fill);
      text(491, top + 8, `${pct.toFixed(0)}%`, 8, palette.muted);
    });
    line(42, 755, 570, 755, palette.line, 0.8);
    text(42, 773, "Generated by Personal Budgeting Tool", 8, palette.muted);

    const stream = ops.join("\n");
    const extraCategories = [...(data.categories || [])].sort((a, b) => b.amount - a.amount).slice(8);
    let detailStream = null;
    if (extraCategories.length) {
      ops = [];
      rect(0, 0, PAGE_W, 105, palette.charcoal);
      text(42, 43, "Additional categories", 23, palette.white, true);
      text(42, 68, data.period || "Budget summary", 11, "#E7EBEF");
      text(42, 145, "Other reported expenses", 13, palette.ink, true);
      text(42, 170, "Category", 9, palette.muted, true);
      text(310, 170, "Group", 9, palette.muted, true);
      text(425, 170, "Amount", 9, palette.muted, true);
      text(520, 170, "Share", 9, palette.muted, true);
      line(42, 180, 570, 180, palette.line, 1);
      extraCategories.forEach((item, i) => {
        const top = 205 + i * 28;
        const pct = Number(item.amount) / Math.max(Number(data.income), 1) * 100;
        text(42, top, ascii(item.name).slice(0, 38), 9, palette.ink);
        text(310, top, item.group, 9, palette.muted);
        text(425, top, money(item.amount), 9, palette.ink);
        text(520, top, `${pct.toFixed(1)}%`, 9, palette.ink);
        line(42, top + 9, 570, top + 9, palette.line, 0.6);
      });
      detailStream = ops.join("\n");
    }
    const objects = [
      "<< /Type /Catalog /Pages 2 0 R >>",
      detailStream
        ? "<< /Type /Pages /Kids [3 0 R 7 0 R] /Count 2 >>"
        : "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
      "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
      "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
      "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
      `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`
    ];
    if (detailStream) {
      objects.push("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 8 0 R >>");
      objects.push(`<< /Length ${detailStream.length} >>\nstream\n${detailStream}\nendstream`);
    }
    let pdf = "%PDF-1.4\n";
    const offsets = [0];
    objects.forEach((object, i) => {
      offsets.push(pdf.length);
      pdf += `${i + 1} 0 obj\n${object}\nendobj\n`;
    });
    const xref = pdf.length;
    pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
    offsets.slice(1).forEach(offset => { pdf += `${String(offset).padStart(10, "0")} 00000 n \n`; });
    pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
    return pdf;
  }

  window.downloadBudgetPdf = json => {
    const data = JSON.parse(json);
    const blob = new Blob([makeReport(data)], { type: "application/pdf" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `budget-report${data.monthly ? `-${data.period.toLowerCase().replace(/[^a-z0-9]+/g, "-")}` : ""}.pdf`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };
})();
